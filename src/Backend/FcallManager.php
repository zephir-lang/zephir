declare(strict_types=1);

namespace Zephir\Backend;

use Zephir\Code\Printer;
use Zephir\FileSystem\HardDisk;

use function array_merge;
use function implode;
use function ksort;
use function sprintf;

class FcallManager implements FcallManagerInterface
{
    protected array $requiredMacros = [];

    public function genFcallCode(): void
    {
        $codePrinter = new Printer();

        $header = <<<HEAD
/*
 * This file was generated automatically by Zephir.
 * DO NOT EDIT THIS FILE BY HAND -- YOUR CHANGES WILL BE OVERWRITTEN
 */

#ifndef ZEPHIR_KERNEL_FCALL_INTERNAL_H
#define ZEPHIR_KERNEL_FCALL_INTERNAL_H

HEAD;
        $codePrinter->output($header);

        ksort($this->requiredMacros);
        foreach ($this->requiredMacros as $name => $info) {
            [$scope, $mode, $paramCount] = $info;
            $paramsStr      = '';
            $retParam       = '';
            $retValueUsed   = '0';
            $params         = [];
            $zvals          = [];
            $initStatements = [];
            $postStatements = [];

            for ($i = 0; $i < $paramCount; ++$i) {
                $params[] = 'p' . $i;
            }
            if ($paramCount) {
                $paramsStr = ', ' . implode(', ', $params);
            }

            if ('CALL_INTERNAL_METHOD_P' == $mode) {
                $retValueUsed     = '1';
                $retParam         = 'return_value_ptr';
                $initStatements[] = 'ZEPHIR_INIT_NVAR((return_value_ptr)); \\';
            }

            /**
             * The method body runs in the scope of the class that declares it,
             * which is not the object's class when the method is inherited:
             * PHP checks every private and protected member the body reaches
             * against that class. The called scope stays the object's class
             * (the class the call names, for a static call).
             *
             * @see https://github.com/zephir-lang/zephir/issues/2734
             */
            $objParam  = $scope ? 'scope_ce, called_ce, ' : 'object, scope_ce, ';
            $macroName = $name . '(' . ($retParam ? $retParam . ', ' : '') . $objParam . 'method' . $paramsStr . ')';
            $codePrinter->output('#define ' . $macroName . ' \\');
            if (!$retParam) {
                $retParam = 'return_value';
            }
            $codePrinter->increaseLevel();
            $codePrinter->output('do { \\');
            $codePrinter->increaseLevel();

            if ('CALL_INTERNAL_METHOD_NORETURN_P' == $mode) {
                $codePrinter->output('zval rv; \\');
                $codePrinter->output('zval *rvp = &rv; \\');
                $codePrinter->output('ZVAL_UNDEF(&rv); \\');
                $retParam = 'rvp';
            }

            /**
             * A static call names the class `static` means in the method. It
             * is read before the frame is replaced, since `self::` passes on
             * the called class of the code that makes the call (#2791).
             */
            if ($scope) {
                $codePrinter->output('zend_class_entry *zephir_called_ce_ = (called_ce); \\');
            }

            /**
             * The frame the method runs on is named after it: the class that
             * declares the method sets up `zephir_frame_<method>` (#2791).
             */
            $codePrinter->output('ZEPHIR_BACKUP_SCOPE(&zephir_frame_##method); \\');
            if (!$scope) {
                $codePrinter->output('ZEPHIR_SET_THIS(object); \\');
                $codePrinter->output(
                    'ZEPHIR_SET_SCOPE(scope_ce, (Z_OBJ_P(object) ? Z_OBJCE_P(object) : NULL)); \\'
                );
            } else {
                $codePrinter->output('ZEPHIR_SET_THIS_EXPLICIT_NULL(); \\');
                $codePrinter->output('ZEPHIR_SET_SCOPE(scope_ce, zephir_called_ce_); \\');
            }

            /**
             * Each argument gets a slot of its own, as in PHP's call frame:
             * the method may separate or overwrite its parameter, and the slot
             * is released after the call. An argument left out is passed as
             * NULL, so the method takes the parameter's default (#2791).
             */
            $slots  = [];
            $copies = [];
            for ($i = 0; $i < $paramCount; ++$i) {
                $zvals[]          = '_' . $params[$i];
                $slots[]          = '_a' . $i;
                $copies[]         = 'zval *_a' . $i . ' = zephir_internal_arg(&_' . $params[$i] . ', ' . $params[$i] . '); \\';
                $postStatements[] = 'zephir_internal_arg_release(_a' . $i . '); \\';
            }
            if ($paramCount) {
                $codePrinter->output('zval ' . implode(', ', $zvals) . '; \\');
            }
            foreach (array_merge($copies, $initStatements) as $statement) {
                $codePrinter->output($statement);
            }

            $codePrinter->output(
                sprintf(
                    'method(0, execute_data, %s, %s%s%s); \\',
                    $retParam,
                    $scope ? 'NULL, ' : 'object, ',
                    $retValueUsed,
                    $paramCount ? ', ' . implode(', ', $slots) : ''
                )
            );

            if ('CALL_INTERNAL_METHOD_NORETURN_P' == $mode) {
                $postStatements[] = 'zval_ptr_dtor(rvp); \\';
            }

            foreach ($postStatements as $statement) {
                $codePrinter->output($statement);
            }

            $codePrinter->output('ZEPHIR_LAST_CALL_STATUS = EG(exception) ? FAILURE : SUCCESS; \\');

            $codePrinter->output('ZEPHIR_RESTORE_SCOPE(); \\');
            $codePrinter->decreaseLevel();
            $codePrinter->output('} while (0)');
            $codePrinter->decreaseLevel();
            $codePrinter->output('');
        }

        $codePrinter->output('#endif');
        HardDisk::persistByHash($codePrinter->getOutput(), 'ext/kernel/fcall_internal.h');
    }

    /**
     * tri-state: 0 -> no return value, 1 -> do return, 2 -> do return to given variable
     */
    public function getMacro(bool $static, int $doReturn, int $paramCount): string
    {
        $scope = $static ? 'STATIC' : '';
        $mode  = 'CALL_INTERNAL_METHOD_NORETURN_P';

        if ($doReturn) {
            $mode = 'RETURN_CALL_INTERNAL_METHOD_P';
            if (2 === $doReturn) {
                $mode = 'CALL_INTERNAL_METHOD_P';
            }
        }

        $macroName = 'ZEPHIR_' . ($scope ? $scope . '_' : '') . $mode . $paramCount;

        if (!isset($this->requiredMacros[$macroName])) {
            $this->requiredMacros[$macroName] = [$scope, $mode, $paramCount];
        }

        return $macroName;
    }
}
